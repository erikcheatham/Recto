def test_profile_store_round_trips_derived_pubkey_hex(tmp_path: Path):
    """v2.0.C: Profile rows with derived_pubkey_hex serialize +
    deserialize cleanly. The field appears on disk only when present
    (None-valued rows omit it entirely — keeps v2.0.B-era blobs
    byte-identical on a load-then-save round-trip)."""
    import json as _json
    from recto.profile.manage import bootstrap_master, create_child_profile
    from recto.profile.store import (
        load_master_identity,
        master_identity_path,
    )

    state_dir = tmp_path / "state"
    state_dir.mkdir(mode=0o700)

    bootstrap_master(
        master_pubkey_hex=bytes(range(64)).hex(),
        state_dir=state_dir,
    )
    # Create one with pubkey, one without (simulates a hypothetical
    # v2.0.B-era persisted row via direct manage.py call without
    # passing derived_pubkey_hex).
    p_with = create_child_profile(
        kind="personal:child",
        display_name="Has pubkey",
        derived_pubkey_hex=FIXTURE_CHILD_PUBKEY_HEX,
        state_dir=state_dir,
    )
    p_without = create_child_profile(
        kind="work",
        display_name="No pubkey",
        state_dir=state_dir,
    )

    # On-disk JSON: with-pubkey row has the field, without-pubkey
    # row omits it (None-omit serialization).
    blob_path = master_identity_path(state_dir)
    raw = _json.loads(blob_path.read_text(encoding="utf-8"))
    rows = {r["profile_id"]: r for r in raw["profiles"]}
    assert rows[p_with.profile_id].get("derived_pubkey_hex") == FIXTURE_CHILD_PUBKEY_HEX
    assert "derived_pubkey_hex" not in rows[p_without.profile_id]

    # Reload and verify the typed dataclass round-trips cleanly.
    mi2 = load_master_identity(state_dir=state_dir)
    assert mi2 is not None
    typed_rows = {p.profile_id: p for p in mi2.profiles}
    assert typed_rows[p_with.profile_id].derived_pubkey_hex == FIXTURE_CHILD_PUBKEY_HEX
    assert typed_rows[p_without.profile_id].derived_pubkey_hex is None


def test_profile_create_c1_rejects_pubkey_hex_with_invalid_length_via_corrupt_blob(
    tmp_path: Path,
):
    """Defense-in-depth: if a corrupted blob has a derived_pubkey_hex
    of wrong length, the loader rejects it (the file gets moved aside
    + load returns None). v2.0.B-shaped rows (no field) are fine;
    only malformed values trigger rejection."""
    import json as _json
    from recto.profile.store import load_master_identity, master_identity_path

    state_dir = tmp_path / "state"
    state_dir.mkdir(mode=0o700)
    blob_path = master_identity_path(state_dir)
    blob_path.parent.mkdir(parents=True, exist_ok=True)
    corrupt_blob = {
        "schema_version": 1,
        "master_pubkey_hex": bytes(range(64)).hex(),
        "master_profile_id": "master-profile-id-fixture",
        "label": None,
        "profiles": [
            {
                "profile_id": "master-profile-id-fixture",
                "kind": "personal:master",
                "display_name": "Personal (master)",
                "derivation": {
                    "purpose": PROFILE_BIP32_PURPOSE,
                    "profile_coin_type": 0,
                    "profile_index": 0,
                },
                "parent_profile_id": None,
                "theme_hint": None,
                "scim_provider": None,
                "deny_actions_inherited": [],
                "created_at_unix": 1700000000,
                "revoked": False,
                "derived_pubkey_hex": "too-short-not-128-chars",
            },
        ],
    }
