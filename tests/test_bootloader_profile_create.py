def test_profile_create_happy_path_end_to_end(profile_server):
    """Full flow: POST create → operator approves via respond →
    bootloader verifies attestation → atomic-writes profile →
    caller polls result → gets approved + profile_id.

    Verifies Milan commitment B: the profile is on disk AFTER respond
    completes (persist last), AND it's discoverable via list_profiles
    even after the result is polled-and-consumed.
    """
    candidate_id = "test-candidate-001"
    status, body = _http_post(
        f"{profile_server['base_url']}/v0.4/profile/create",
        {
            "phone_id": profile_server["phone_id"],
            "candidate_profile_id": candidate_id,
            "kind": "personal:child",
            "display_name": "Personal pseudonym",
            "operation_description": "Test happy path",
        },
        headers=_agent_headers(),
    )
    assert status == 201
    assert body["candidate_profile_id"] == candidate_id
    request_id = body["request_id"]
    result_url = body["result_url"]

    # Caller's first poll BEFORE the phone approves — should be pending.
    status, body = _http_get(
        f"{profile_server['base_url']}{result_url}",
        headers=_agent_headers(),
    )
    assert status == 200
    assert body["status"] == "pending"

    # Simulate phone approval. Need to know the canonical signing input
    # the bootloader stashed at queue time; re-build it from the
    # candidate fields + known derivation slot.
    mi = profile_server["master_identity"]
    coin_type = _resolve_coin_type("personal:child")
    # The first child profile in this slot — index 0 since master is
    # at coin_type=0 (personal:master), child is at coin_type=1.
    deriv_index = _next_profile_index(mi, coin_type)
    signing_input = _build_signing_input(
        candidate_profile_id=candidate_id,
        kind="personal:child",
        display_name="Personal pseudonym",
        coin_type=coin_type,
        derivation_index=deriv_index,
        master_pubkey_hex=mi.master_pubkey_hex,
    )
    digest = hashlib.sha256(signing_input).digest()
    payload_hash_b64u = _b64u_encode(digest)

    status, body = _approve_via_respond(
        profile_server, request_id, payload_hash_b64u, signing_input,
        child_pubkey_hex=FIXTURE_CHILD_PUBKEY_HEX,
    )
    assert status == 200, f"respond returned {status}: {body}"
    assert body["resolved"] is True

    # Persist-last (Milan B): the new profile should be on disk NOW.
    profiles = list_profiles(state_dir=profile_server["state_dir"])
    matching = [p for p in profiles if p.profile_id == candidate_id]
    assert len(matching) == 1, (
        f"expected exactly 1 profile with candidate_profile_id={candidate_id}, "
        f"got {[(p.profile_id, p.kind, p.display_name) for p in profiles]}"
    )
    new_profile = matching[0]
    assert new_profile.kind == "personal:child"
    assert new_profile.display_name == "Personal pseudonym"
    assert new_profile.derivation.purpose == PROFILE_BIP32_PURPOSE
    assert new_profile.derivation.profile_coin_type == coin_type
    assert new_profile.derivation.profile_index == deriv_index
    assert new_profile.parent_profile_id == mi.master_profile_id

    # Caller's second poll — should be approved + carry the profile_id.
    status, body = _http_get(
        f"{profile_server['base_url']}{result_url}",
        headers=_agent_headers(),
    )
    assert status == 200
    assert body["status"] == "approved"
    assert body["profile_id"] == candidate_id

    # Third poll — result is single-use; should 404.
    status, body = _http_get(
        f"{profile_server['base_url']}{result_url}",
        headers=_agent_headers(),
    )
    assert status == 404

    # BUT the profile is still on disk (Milan B verification).
    profiles_after = list_profiles(state_dir=profile_server["state_dir"])
    assert any(p.profile_id == candidate_id for p in profiles_after), (
        "profile must remain on disk even after result-store consumption"
    )


