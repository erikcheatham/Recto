def test_profile_create_rejects_signature_signed_by_non_operator(profile_server):
    """A signature that doesn't recover to the configured operator
    pubkey → signature_error status; no profile created (Milan C)."""
    candidate_id = "test-bad-sig"
    status, body = _http_post(
        f"{profile_server['base_url']}/v0.4/profile/create",
        {
            "phone_id": profile_server["phone_id"],
            "candidate_profile_id": candidate_id,
            "kind": "personal:child",
            "display_name": "Bad-sig profile",
        },
        headers=_agent_headers(),
    )
    assert status == 201
    request_id = body["request_id"]

    # Build the correct signing input but sign with a DIFFERENT key
    # — bootloader's recovery won't match the configured operator
    # pubkey.
    mi = profile_server["master_identity"]
    coin_type = _resolve_coin_type("personal:child")
    deriv_index = _next_profile_index(mi, coin_type)
    signing_input = _build_signing_input(
        candidate_profile_id=candidate_id,
        kind="personal:child",
        display_name="Bad-sig profile",
        coin_type=coin_type,
        derivation_index=deriv_index,
        master_pubkey_hex=mi.master_pubkey_hex,
    )
    digest = hashlib.sha256(signing_input).digest()
    payload_hash_b64u = _b64u_encode(digest)

    # Phase 2.0.C wave C.1: sign over the FULL canonical JSON
    # (partial fields + child_pubkey_hex) — the bootloader's verify
    # path reconstructs the same input server-side and recovers the
    # signature against the operator pubkey. Test uses a DIFFERENT
    # secp256k1 key so recovery yields wrong_priv's pubkey, NOT the
    # operator's → bootloader rejects with "did not recover."
    partial_fields = json.loads(signing_input.decode("utf-8"))
    partial_fields["child_pubkey_hex"] = FIXTURE_CHILD_PUBKEY_HEX
    full_signing_input = _canonical_json(partial_fields)
    full_digest = hashlib.sha256(full_signing_input).digest()

    # Sign with a DIFFERENT key.
    from cryptography.hazmat.backends import default_backend
    from cryptography.hazmat.primitives.asymmetric import ec
    wrong_priv = ec.generate_private_key(ec.SECP256K1(), default_backend())
    wrong_priv_int = wrong_priv.private_numbers().private_value
    cap_sig_bytes = _sign_master_attestation(full_digest, wrong_priv_int)
    cap_sig_b64u = _b64u_encode(cap_sig_bytes)

    # Ed25519 envelope still valid — the bootloader gets past the
    # envelope check and into the master-attestation branch.
    hash_bytes = _b64u_decode(payload_hash_b64u)
    ed_sig = profile_server["ed_priv"].sign(hash_bytes)
    ed_sig_b64u = _b64u_encode(ed_sig)

    status, body = _http_post(
        f"{profile_server['base_url']}/v0.4/respond/{request_id}",
        {
            "decision": "approved",
            "signature_b64u": ed_sig_b64u,
            "cap_signature_b64u": cap_sig_b64u,
            "child_pubkey_hex": FIXTURE_CHILD_PUBKEY_HEX,
        },
    )
    # _handle_respond raises BootloaderError on signature-mismatch
    # → caught by do_POST, returns 400 bootloader_error.
    assert status == 400
    assert "did not recover" in body["detail"] or "did not recover" in body.get("error", "")

    # Profile should NOT exist on disk (Milan C — never lie about success).
    profiles = list_profiles(state_dir=profile_server["state_dir"])
    assert not any(p.profile_id == candidate_id for p in profiles)

    # Result store should carry signature_error status with reason.
    # NOTE: result is single-use; this is the first read.
    status, body = _http_get(
        f"{profile_server['base_url']}/v0.4/profile/result/{request_id}",
        headers=_agent_headers(),
    )
    assert status == 200
    assert body["status"] == "signature_error"
    assert "did not recover" in body["reason"] or "operator pubkey" in body["reason"]


