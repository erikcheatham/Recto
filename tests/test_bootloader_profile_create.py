"""Tests for Phase 2.0.B integration: the bootloader's HTTP surface for
profile_create (multi-profile identity).

Covers two new endpoints + the _handle_respond profile_create branch:

1. ``POST /v0.4/profile/create`` — agent-token-authenticated; queues a
   profile_create PendingRequest on the operator's paired phone with
   the candidate Profile shape. Returns request_id + result_url +
   echo of the caller-authored ``candidate_profile_id`` (idempotency
   key).
2. ``GET /v0.4/profile/result/<request_id>`` — agent-token + ownership
   pin; single-use poll for the post-approval result.
3. ``POST /v0.4/respond/<request_id>`` (profile_create branch) — phone
   posts a master-attestation signature over the canonical-JSON
   encoding of the candidate fields; bootloader verifies against
   ``cfg.capability_operator_pubkey``, atomic-writes the new Profile
   via ``profile.manage.create_child_profile``, stashes a
   ProfileCreateResult.

Partial-failure design (Milan Jovanović's commitments A-C):

* **A — caller-authored idempotency key**: ``candidate_profile_id`` is
  generated by the test caller (mirroring the real CLI / SCIM glue);
  re-submit with the same key returns the existing profile WITHOUT
  re-prompting the phone.
* **B — persist last; result is derived**: assertions on the on-disk
  master_identity.json being source of truth; the in-memory result
  store is a poll-convenience layer.
* **C — never claim success when persist failed**: tests covering
  the "phone signed wrong" path (signature_error) AND the persist-error
  path (signature_error with "persist_error:" reason prefix).

Test-only master attestation signing uses the ``cryptography`` lib's
secp256k1 support — same pattern as ``test_bootloader_capability_gate.py``.
Production mint flow stays phone-enclave-only.
"""

