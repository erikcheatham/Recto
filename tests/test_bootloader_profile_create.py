def _approve_via_respond(
    ctx: dict[str, Any],
    request_id: str,
    payload_hash_b64u: str,
    signing_input_bytes: bytes,
    *,
    child_pubkey_hex: str | None = None,
    omit_child_pubkey_hex: bool = False,
    override_cap_signature_b64u: str | None = None,
) -> tuple[int, dict[str, Any]]:
    """Simulate the phone approving a profile_create request.

    Phase 2.0.C wave C.1: the response body now requires
    ``child_pubkey_hex`` alongside ``cap_signature_b64u`` (v2.0.B
    shape is rejected with protocol_violation). The secp256k1 master
    attestation signs over the FULL canonical JSON (queue-time
    candidate fields + child_pubkey_hex), NOT the partial signing
    input the queue-time bootloader stashed.

    1. Signs the Ed25519 paired-phone envelope over the payload hash
       bytes from the queue-time partial signing input (bootloader's
       _handle_respond verifies this first; unchanged from v2.0.B).
    2. Builds the FULL canonical JSON by parsing
       ``signing_input_bytes`` (the queue-time partial), adding
       ``child_pubkey_hex``, re-canonicalizing with the same
       encoder the bootloader uses.
    3. Signs the secp256k1 master attestation over SHA-256(full
       signing input) — this is what the bootloader's verify path
       reconstructs and matches against.
    4. POSTs the response back with both sigs + the pubkey.

    Args:
        child_pubkey_hex: the 128-hex secp256k1 pubkey the phone
            "derived" from the master at the candidate's path. v2.0.C
            wire shape requires this. Tests that want to exercise
            the malformed-pubkey rejection paths pass an invalid
            value; tests that want to exercise the missing-field
            rejection pass ``omit_child_pubkey_hex=True`` instead.
        omit_child_pubkey_hex: when True, skip the field on the
            response body entirely (simulates a v2.0.B-shaped phone
            client). Bootloader should reject with
            protocol_violation.
        override_cap_signature_b64u: when set, use this signature
            instead of computing one — for tests that want to
            exercise sig-shape rejection (wrong length, garbage
            base64, signed-by-wrong-key, etc.).
    """
    # Ed25519 envelope sig (unchanged from v2.0.B)
    hash_bytes = _b64u_decode(payload_hash_b64u)
    ed_sig = ctx["ed_priv"].sign(hash_bytes)
    ed_sig_b64u = _b64u_encode(ed_sig)

    # v2.0.C: reconstruct the FULL canonical JSON for the master
    # attestation. The bootloader's verify path does the same:
    # parses signing_input_bytes (the queue-time partial) back to
    # dict, injects child_pubkey_hex, re-canonicalizes, SHA-256s.
    if child_pubkey_hex is None and not omit_child_pubkey_hex:
        raise ValueError(
            "test helper bug: child_pubkey_hex required unless "
            "omit_child_pubkey_hex=True (v2.0.C wire shape)"
        )

    if omit_child_pubkey_hex:
        # Signing over the partial — this is what a v2.0.B client
        # would have done. The signature will not match what the
        # bootloader reconstructs (it expects the full JSON), so
        # tests that omit the field expect the bootloader's
        # protocol_violation rejection BEFORE the signature
        # comparison anyway.
        digest = hashlib.sha256(signing_input_bytes).digest()
    else:
        partial_fields = json.loads(signing_input_bytes.decode("utf-8"))
        partial_fields["child_pubkey_hex"] = child_pubkey_hex
        full_signing_input = _canonical_json(partial_fields)
        digest = hashlib.sha256(full_signing_input).digest()

    if override_cap_signature_b64u is not None:
        cap_sig_b64u = override_cap_signature_b64u
    else:
        cap_sig_bytes = _sign_master_attestation(digest, ctx["priv_int"])
        cap_sig_b64u = _b64u_encode(cap_sig_bytes)

    body: dict[str, Any] = {
        "decision": "approved",
        "signature_b64u": ed_sig_b64u,
        "cap_signature_b64u": cap_sig_b64u,
    }
    if not omit_child_pubkey_hex:
        body["child_pubkey_hex"] = child_pubkey_hex
    return _http_post(
        f"{ctx['base_url']}/v0.4/respond/{request_id}",
        body,
    )


def _build_signing_input(
    *,
    candidate_profile_id: str,
    kind: str,
    display_name: str,
    coin_type: int,
    derivation_index: int,
    theme_hint: str | None = None,
    scim_provider: str | None = None,
    master_pubkey_hex: str,
) -> bytes:
    """Reconstruct the QUEUE-TIME (partial) canonical-JSON signing
    input the bootloader stashes in cap_payload_b64.

    The partial form does NOT include child_pubkey_hex — that's
    added by the phone at approval time before signing. Test helper
    that mirrors what _handle_profile_create does at queue time so
    tests can verify the digest match independently. Tests that
    want the FULL form (the bytes the phone actually signs over)
    pass this output to _approve_via_respond with the desired
    child_pubkey_hex; the helper does the parse + inject + re-
    canonicalize itself.
    """
    candidate_fields = {
        "candidate_profile_id": candidate_profile_id,
        "kind": kind,
        "display_name": display_name,
        "derivation_purpose": PROFILE_BIP32_PURPOSE,
        "derivation_coin_type": coin_type,
        "derivation_index": derivation_index,
        "theme_hint": theme_hint,
        "scim_provider": scim_provider,
        "master_pubkey_hex": master_pubkey_hex,
    }
    return _canonical_json(candidate_fields)


